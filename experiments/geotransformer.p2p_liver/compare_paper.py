"""Summarize GeoTransformer P2P evaluations against released paper results."""

import argparse
import csv
import json
import os
import os.path as osp
import sys


METHOD_ORDER = (
    "GeoTransformer",
    "LiverMatch",
    "LiverMatch+P2P",
    "Lepard",
    "Lepard+P2P",
    "RegTr",
    "RoITr",
)


def make_parser():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "summaries",
        nargs="+",
        help="test_noise_*_summary.json files generated by test.py",
    )
    parser.add_argument("--output", default=None, help="output comparison CSV")
    return parser


def _low_visibility(summary):
    for row in summary["visibility_bins"]:
        if row["range"] == "[0.2, 0.3]":
            return row
    raise KeyError("Visibility bin [0.2, 0.3] is missing from the summary.")


def _noise_label(value):
    return "none" if value is None else f"{value} mm"


def _format_metric(mean, std):
    if mean is None or std is None:
        return "n/a"
    return f"{mean:.4f} +/- {std:.4f}"


def _print_table(title, rows):
    columns = (
        ("method", "Method"),
        ("overall", "Overall RMS-TRE (mm)"),
        ("low_visibility", "RMS-TRE [0.2,0.3] (mm)"),
        ("overall_sr", "Overall SR@20mm"),
        ("low_visibility_sr", "SR@20mm [0.2,0.3]"),
        ("delta_low", "Delta low-vis (mm)"),
    )
    widths = []
    for key, heading in columns:
        widths.append(max(len(heading), *(len(str(row[key])) for row in rows)))
    print(f"\n{title}")
    print(" | ".join(heading.ljust(width) for (_, heading), width in zip(columns, widths)))
    print("-+-".join("-" * width for width in widths))
    for row in rows:
        print(" | ".join(str(row[key]).ljust(width) for (key, _), width in zip(columns, widths)))


def main():
    args = make_parser().parse_args()
    csv_rows = []
    first_dir = None

    for path in args.summaries:
        path = osp.abspath(path)
        if first_dir is None:
            first_dir = osp.dirname(path)
        with open(path, encoding="utf-8") as handle:
            payload = json.load(handle)

        expected = int(payload["dataset_size"])
        evaluated = int(payload["evaluated_samples"])
        if evaluated != expected:
            print(
                f"WARNING: {path} evaluated {evaluated}/{expected} samples; "
                "the comparison is not a full-dataset result.",
                file=sys.stderr,
            )

        summaries = {"GeoTransformer": payload["GeoTransformer"]}
        summaries.update(payload.get("paper_references", {}))
        geo_low = _low_visibility(payload["GeoTransformer"])["mean_rms_tre_mm"]
        display_rows = []

        for method in METHOD_ORDER:
            if method not in summaries:
                continue
            summary = summaries[method]
            low = _low_visibility(summary)
            low_mean = low["mean_rms_tre_mm"]
            delta_low = 0.0 if method == "GeoTransformer" else geo_low - low_mean
            row = {
                "noise": _noise_label(payload.get("noise_mm")),
                "method": method,
                "count": int(summary["count"]),
                "overall_rms_tre_mean_mm": summary["mean_rms_tre_mm"],
                "overall_rms_tre_std_mm": summary["std_rms_tre_mm"],
                "low_visibility_count": int(low["count"]),
                "low_visibility_rms_tre_mean_mm": low_mean,
                "low_visibility_rms_tre_std_mm": low["std_rms_tre_mm"],
                "overall_success_rate_20mm": summary["success_rate_20mm"],
                "low_visibility_success_rate_20mm": low["success_rate_20mm"],
                "geotransformer_minus_method_low_visibility_mm": delta_low,
            }
            csv_rows.append(row)
            display_rows.append(
                {
                    "method": method,
                    "overall": _format_metric(
                        row["overall_rms_tre_mean_mm"], row["overall_rms_tre_std_mm"]
                    ),
                    "low_visibility": _format_metric(
                        row["low_visibility_rms_tre_mean_mm"],
                        row["low_visibility_rms_tre_std_mm"],
                    ),
                    "overall_sr": f"{row['overall_success_rate_20mm'] * 100:.2f}%",
                    "low_visibility_sr": (
                        f"{row['low_visibility_success_rate_20mm'] * 100:.2f}%"
                    ),
                    "delta_low": f"{delta_low:+.4f}",
                }
            )

        _print_table(
            f"Noise: {_noise_label(payload.get('noise_mm'))} "
            f"({evaluated}/{expected} evaluated)",
            display_rows,
        )

    output = osp.abspath(args.output or osp.join(first_dir, "paper_comparison.csv"))
    os.makedirs(osp.dirname(output), exist_ok=True)
    with open(output, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(csv_rows[0]))
        writer.writeheader()
        writer.writerows(csv_rows)
    print(f"\nComparison CSV written to {output}")


if __name__ == "__main__":
    main()
